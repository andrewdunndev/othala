//! `client_data`: the input as the `clientDataJSON` of an assertion response, with the control assertion's
//! authenticator data.
use webauthn_rp::{AuthenticationResponse, ErrorKind};

const AUTHENTICATOR_DATA: [u8; 37] = [
    0xbf, 0xab, 0xc3, 0x74, 0x32, 0x95, 0x8b, 0x06, 0x33, 0x60, 0xd3, 0xad, 0x64, 0x61, 0xc9, 0xc4,
    0x73, 0x5a, 0xe7, 0xf8, 0xed, 0xd4, 0x65, 0x92, 0xa5, 0xe0, 0xf0, 0x14, 0x52, 0xb2, 0xe4, 0xb5,
    0x05, 0x00, 0x00, 0x00, 0x06,
];

pub(crate) fn check(data: &[u8]) -> Result<(), ErrorKind> {
    AuthenticationResponse::new(&[1; 16], data, &AUTHENTICATOR_DATA, &[], None)
        .map(drop)
        .map_err(|e| e.kind())
}
