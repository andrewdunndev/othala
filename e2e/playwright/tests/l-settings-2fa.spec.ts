/**
 * L — Settings page: TOTP + lookup_secret (backup codes) rendering.
 *
 * Coverage gap addressed: the settings/2FA page had ZERO browser-driven e2e
 * coverage for the nodes that carry enrollment secrets. This spec proves that:
 *
 *   L1 — TOTP enrollment surface:
 *     The settings page renders a QR code img and the raw secret text node
 *     when Kratos has a TOTP enrollment in progress. This confirms the img/text
 *     node dispatch in settings.astro is live (not dead-code).
 *
 *   L2 — Backup code generation surface (the test that exposes bug #1):
 *     After triggering "Generate backup codes" via the lookup_secret form,
 *     the settings page re-renders with the generated codes VISIBLE in the
 *     HTML. Pre-fix, FlowNodes/asInput() silently drops node_type:"text"
 *     nodes, so the codes are generated by Kratos but never shown. This
 *     assertion fails on the un-fixed page and passes after the fix.
 *
 * Pattern:
 *   1. Seed a fresh identity via the Kratos admin API.
 *   2. Log in (password → JSON-API path) to get a privileged session. The
 *      Kratos settings flow requires a privileged session (within
 *      privileged_session_max_age), so login must happen immediately before
 *      navigating to /auth/settings.
 *   3. Navigate to /auth/settings and assert the flow is rendered (the page
 *      does NOT redirect to login).
 *   4. For L1: initiate a TOTP settings flow via the Kratos API and assert
 *      the settings page renders the QR img and/or secret text.
 *   5. For L2: locate and submit the lookup_secret "Generate backup codes"
 *      form, then assert the response HTML contains visible backup code text
 *      (data-testid="backup-codes" is non-empty).
 *
 * Live-stack requirements:
 *   - Kratos TOTP strategy + lookup_secret strategy enabled in kratos.yml.
 *   - The `browser` + `kratos` + `othala` compose services are running.
 *   - The identity schema allows both TOTP and lookup_secret credentials.
 *   - privileged_session_max_age ≥ 15m (default in othala's kratos.yml).
 *
 * Node-shape assumptions (live confirmation recommended):
 *   - TOTP enrollment: Kratos emits a node_type:"img" (QR) and a
 *     node_type:"text" (secret) in group:"totp" when TOTP enrollment is
 *     in progress. The text node carries the TOTP secret in attributes.text.text.
 *   - Backup codes: after submitting the "reveal_code" action, Kratos emits
 *     a node_type:"text" in group:"lookup_secret" whose attributes.text.text
 *     contains the backup codes (newline-separated or comma-separated).
 *     The data-testid="backup-codes" selector targets this rendered element.
 *   - The form submission for lookup_secret uses method="POST" on ui.action,
 *     with the hidden inputs `csrf_token`, `method=lookup_secret`, and
 *     `lookup_secret_confirm=true` (the "generate" trigger in Kratos).
 */

